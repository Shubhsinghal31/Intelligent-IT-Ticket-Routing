"""
Database bootstrap — brings a Postgres database from empty to fully
migrated and seeded, idempotently, in one command.

Why this exists
----------------
This project's schema history has two eras: 10 hand-written SQL files
(database/migrations/001-010) that predate Alembic, followed by
Alembic-managed migrations layered on top (alembic/versions/). Alembic's
baseline revision (879b53d74f82) is a deliberate no-op — it was
autogenerated to mark "the schema at this point", assuming 001-010 had
already been applied by hand. That means `alembic upgrade head` alone
does nothing useful against a brand-new, empty database: it needs
001-010 applied first.

That two-step reality was manageable when it only had to happen once,
by hand, on a developer's own machine. It stops being manageable the
moment a container needs to bootstrap itself — `docker compose up`
should bring an empty database to a fully working one without a human
running `psql` commands in between. This script makes that two-step
process a single, idempotent function instead of a manual runbook.

Idempotency
-----------
- Legacy SQL (001-010): only applied if the `users` table doesn't exist
  yet. These files are NOT safe to re-run (CREATE TYPE/CREATE TABLE
  fail on a second run), so they're gated behind an existence check.
- Alembic migrations: `alembic upgrade head` is naturally idempotent —
  it tracks the current revision in its own `alembic_version` table and
  no-ops if already at head.
- Seed data (roles, departments, SLA policies, admin user): every seed
  file uses `ON CONFLICT ... DO NOTHING`, so re-running them against an
  already-seeded database is a safe no-op. They're re-applied on every
  bootstrap run rather than gated, since "safe to repeat" is simpler to
  reason about than "detect if already seeded".

Deliberately excluded: database/migrations/011 and 012. Those two files
duplicate what the Alembic revisions b47d9a1e6c33 and c58ea2f7d144
already do (the timestamp-timezone fix and the password_reset_tokens
table) — they were left in migrations/ as a historical record of what
was manually applied before Alembic adoption, not as something this
script should also run. Applying both would either double-run the same
DDL or conflict outright.

Usage
-----
    python -m database.bootstrap

Used automatically by docker/docker-compose.yml's backend service
command. For a native (non-Docker) setup, this same command can replace
the manual "run 001-010, then alembic stamp/upgrade, then run seeds"
sequence documented in database/README.md.
"""

from __future__ import annotations

import subprocess
import sys
from pathlib import Path

import psycopg2

from backend.core.config import settings

MIGRATIONS_DIR = Path(__file__).parent / "migrations"
SEEDS_DIR = Path(__file__).parent / "seeds"

# Only 001 through 010 predate Alembic — see module docstring for why
# 011/012 are deliberately excluded.
_LEGACY_PREFIXES = tuple(f"{i:03d}_" for i in range(1, 11))


def _schema_already_bootstrapped(conn) -> bool:
    """
    True if the legacy schema (001-010) has already been applied.

    `to_regclass()` returns NULL for a table that doesn't exist, and the
    table's OID (non-NULL) if it does — cheaper and simpler than
    querying information_schema, and doesn't raise if the table is
    missing (unlike a bare SELECT against it would).
    """
    with conn.cursor() as cur:
        cur.execute("SELECT to_regclass('public.users')")
        return cur.fetchone()[0] is not None


def _run_sql_file(conn, path: Path) -> None:
    """
    Execute an entire .sql file as one statement batch.

    psycopg2 sends a parameter-free execute() string to Postgres via the
    simple query protocol, which supports multiple semicolon-separated
    statements natively — including ones with dollar-quoted bodies. That
    means this doesn't need to (and shouldn't) split the file on ";"
    itself; Postgres's own parser handles that correctly.
    """
    sql = path.read_text(encoding="utf-8")
    with conn.cursor() as cur:
        cur.execute(sql)
    conn.commit()


def _apply_legacy_migrations(conn) -> None:
    if _schema_already_bootstrapped(conn):
        print("[bootstrap] Legacy schema (001-010) already present — skipping.")
        return

    print("[bootstrap] Empty database detected — applying legacy schema (001-010)...")
    legacy_files = sorted(
        p for p in MIGRATIONS_DIR.glob("*.sql") if p.name.startswith(_LEGACY_PREFIXES)
    )
    for path in legacy_files:
        print(f"[bootstrap]   applying {path.name}")
        _run_sql_file(conn, path)


def _apply_seeds(conn) -> None:
    print("[bootstrap] Applying seed data (idempotent, safe to repeat)...")
    for path in sorted(SEEDS_DIR.glob("*.sql")):
        print(f"[bootstrap]   seeding {path.name}")
        _run_sql_file(conn, path)


def bootstrap() -> None:
    """Run the full bootstrap sequence: legacy schema, Alembic, seeds."""
    conn = psycopg2.connect(str(settings.DATABASE_URL))
    try:
        _apply_legacy_migrations(conn)
    finally:
        conn.close()

    print("[bootstrap] Running Alembic migrations (upgrade head)...")
    subprocess.run([sys.executable, "-m", "alembic", "upgrade", "head"], check=True)

    conn = psycopg2.connect(str(settings.DATABASE_URL))
    try:
        _apply_seeds(conn)
    finally:
        conn.close()

    print("[bootstrap] Done — database is fully migrated and seeded.")


if __name__ == "__main__":
    bootstrap()
